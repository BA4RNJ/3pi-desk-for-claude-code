/**
 * WSL, with or without WSLg, has no Windows system tray and cannot receive
 * Windows-wide global shortcuts. Detect it once at startup so those features
 * can degrade without changing behavior on native Linux.
 */
function detectWsl(): boolean {
  let osRelease = ''
  try {
    osRelease = readFileSync('/proc/sys/kernel/osrelease', 'utf8')
  } catch {
    // /proc is unavailable outside Linux; the environment markers are enough.
  }
  return isWslEnvironment(process.env, osRelease)
}

const runningUnderWsl = detectWsl()

/**
 * Keep the X11 WM_CLASS in sync with the desktop entry generated by
 * electron-builder. The regular build uses `3pi-desk`; the WSL build overrides
 * `desktopName` to `3pi-desk-wsl` so both editions can coexist.
 */
function windowClass(): string {
  try {
    const pkg = JSON.parse(
      readFileSync(join(app.getAppPath(), 'package.json'), 'utf8')
    ) as { desktopName?: string }
    const name = pkg.desktopName?.trim().replace(/\.desktop$/i, '')
    if (name) return name
  } catch {
    // Fall through to the executable name.
  }
  return app.isPackaged ? basename(process.execPath) : '3pi-desk'
}

if (process.platform === 'linux') {
  app.commandLine.appendSwitch('class', windowClass())
}

