function showWindow(): void {
  // Unhide the app itself on macOS (e.g. after Cmd+H) before focusing a window.
  if (process.platform === 'darwin') app.show()
  if (!mainWindow) {
    createWindow()
    return
  }
  if (mainWindow.isMinimized()) mainWindow.restore()
  mainWindow.show()
  mainWindow.focus()
}

function syncGlobalShortcut(enabled: boolean): void {
  globalShortcut.unregister('CommandOrControl+Shift+Space')
  if (enabled && !runningUnderWsl) {
    try {
      globalShortcut.register('CommandOrControl+Shift+Space', showWindow)
    } catch {
      // Wayland or another app may reserve the shortcut.
    }
  }
}

function openSettings(): void {
  if (BrowserWindow.getAllWindows().length === 0) {
    createWindow()
    mainWindow?.webContents.once('did-finish-load', () => {
      mainWindow?.webContents.send('app:open-settings')
    })
    return
  }
  showWindow()
  mainWindow?.webContents.send('app:open-settings')
}

/**
 * macOS requires an application menu for the standard shortcuts (Cmd+C/V/A,
 * Cmd+Q, Cmd+W) to work. Windows/Linux keep the frameless, menu-less layout.
 */
function installApplicationMenu(): void {
  if (process.platform !== 'darwin') {
    Menu.setApplicationMenu(null)
    return
  }

  const viewItems: MenuItemConstructorOptions[] = app.isPackaged
    ? [
        { role: 'resetZoom' },
        { role: 'zoomIn' },
        { role: 'zoomOut' },
        { type: 'separator' },
        { role: 'togglefullscreen' }
      ]
    : [
        { role: 'reload' },
        { role: 'forceReload' },
        { role: 'toggleDevTools' },
        { type: 'separator' },
        { role: 'resetZoom' },
        { role: 'zoomIn' },
        { role: 'zoomOut' },
        { type: 'separator' },
        { role: 'togglefullscreen' }
      ]

  Menu.setApplicationMenu(
    Menu.buildFromTemplate([
      {
        label: '3PI Desk for Claude Code',
        submenu: [
          { role: 'about' },
          {
            label: 'Settings…',
            accelerator: 'Cmd+,',
            click: openSettings
          },
          { type: 'separator' },
          { role: 'services' },
          { type: 'separator' },
          { role: 'hide' },
          { role: 'hideOthers' },
          { role: 'unhide' },
          { type: 'separator' },
          { role: 'quit' }
        ]
      },
      { label: 'File', submenu: [{ role: 'close' }] },
      { role: 'editMenu' },
      { label: 'View', submenu: viewItems },
      { role: 'windowMenu' }
    ])
  )
}

function createTray(): void {
  if (tray) return
  try {
    const image = nativeImage.createFromPath(trayIconPath())
    if (process.platform === 'darwin') {
      image.setTemplateImage(true)
      tray = new Tray(image)
    } else {
      tray = new Tray(image.resize({ width: 22, height: 22 }))
    }
    trayAvailable = true
    tray.setToolTip('3PI Desk')
    tray.setContextMenu(
      Menu.buildFromTemplate([
        { label: 'Show 3PI Desk', click: showWindow },
        {
          label: 'New chat',
          click: () => {
            showWindow()
            mainWindow?.webContents.send('app:new-tab')
          }
        },
        { type: 'separator' },
        {
          label: 'Quit',
          click: () => {
            quitting = true
            app.quit()
          }
        }
      ])
    )
    // On macOS the context menu opens on left click; toggling the window here
    // as well would fight the native menu behavior.
    if (process.platform !== 'darwin') {
      tray.on('click', () => {
        if (mainWindow?.isVisible()) mainWindow.hide()
        else showWindow()
      })
    }
  } catch {
    // Tray may be unavailable in some desktop environments.
  }
}

const hasSingleInstanceLock = app.requestSingleInstanceLock()

if (!hasSingleInstanceLock) {
  app.quit()
} else {
  app.on('second-instance', () => {
    if (app.isReady()) showWindow()
  })
}

if (hasSingleInstanceLock) {
  app.whenReady().then(() => {
    // Finder-launched macOS apps miss the login shell PATH; restore it before
    // any child process (Claude Code tools, plugins, background sessions) runs.
    ensureMacPath()
    installApplicationMenu()
    if (process.platform === 'darwin') {
      app.setAboutPanelOptions({
        applicationName: '3PI Desk for Claude Code',
        applicationVersion: app.getVersion(),
        copyright: 'Copyright © 2026 BA4RNJ',
        credits: 'Powered by the Claude Agent SDK'
      })
      // In development the bundle icon is Electron's; show the product icon.
      if (!app.isPackaged) app.dock?.setIcon(appIconPath())
    }
    registerIpc()
    createWindow()
    if (runningUnderWsl) {
      // WSLg has no tray host, and global shortcuts do not cross into Windows.
      syncGlobalShortcut(false)
    } else {
      createTray()
      syncGlobalShortcut(getPreferences().globalShortcut)
    }

    app.on('activate', () => {
      if (BrowserWindow.getAllWindows().length === 0) createWindow()
      else showWindow()
    })
  })
}

app.on('window-all-closed', () => {
  if (process.platform === 'darwin') {
    // macOS apps stay running without windows; the Dock/tray can reopen the UI.
    for (const manager of managers.values()) void manager.stop()
    managers.clear()
    return
  }
  if (trayAvailable && getPreferences().closeToTray && !quitting) return
  for (const manager of managers.values()) void manager.stop()
  managers.clear()
  app.quit()
})

app.on('before-quit', () => {
  quitting = true
  globalShortcut.unregisterAll()
  for (const manager of managers.values()) void manager.stop()
  managers.clear()
})
