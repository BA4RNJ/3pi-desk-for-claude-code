function send(channel: string, payload: unknown): void {
  if (mainWindow && !mainWindow.isDestroyed()) {
    mainWindow.webContents.send(channel, payload)
  }
}

/**
 * Resolve the app icon outside the asar when packaged. `nativeImage` cannot
 * reliably decode an image path that lives inside app.asar, which left the
 * X11 window without `_NET_WM_ICON` and the tray with an empty image.
 */
function appIconPath(): string {
  const packaged = join(process.resourcesPath, 'icon.png')
  if (existsSync(packaged)) return packaged
  return join(app.getAppPath(), 'resources', 'icon.png')
}

/**
 * macOS menu-bar icons should be monochrome template images so AppKit can
 * adapt them to light/dark menu bars. Other platforms keep the full-color icon.
 */
function trayIconPath(): string {
  if (process.platform !== 'darwin') return appIconPath()
  const packaged = join(process.resourcesPath, 'trayTemplate.png')
  if (existsSync(packaged)) return packaged
  return join(app.getAppPath(), 'resources', 'trayTemplate.png')
}

function isSafeExternalUrl(url: string): boolean {
  try {
    const parsed = new URL(url)
    return parsed.protocol === 'http:' || parsed.protocol === 'https:'
  } catch {
    return false
  }
}

function spawnDetached(
  command: string,
  args: string[],
  fallback?: () => void
): void {
  try {
    const child = spawn(command, args, { detached: true, stdio: 'ignore' })
    let failed = false
    child.on('error', () => {
      if (failed) return
      failed = true
      fallback?.()
    })
    child.unref()
  } catch {
    fallback?.()
  }
}

function windowsPath(path: string): Promise<string | null> {
  return new Promise((resolve) => {
    execFile('wslpath', ['-w', path], (error, stdout) => {
      if (error) resolve(null)
      else resolve(stdout.trim() || null)
    })
  })
}

async function openExternalUrl(url: string): Promise<void> {
  if (!isSafeExternalUrl(url)) return
  if (runningUnderWsl) {
    // explorer.exe hands http(s) URLs to the Windows default browser without
    // invoking cmd.exe argument parsing.
    spawnDetached('explorer.exe', [url], () => {
      void shell.openExternal(url).catch(() => undefined)
    })
    return
  }
  try {
    await shell.openExternal(url)
  } catch {
    // Ignore; there is no better fallback.
  }
}

async function openPathExternally(path: string): Promise<void> {
  if (runningUnderWsl) {
    const winPath = await windowsPath(path)
    if (winPath) {
      // explorer.exe opens directories in Explorer and files with their
      // Windows default application.
      spawnDetached('explorer.exe', [winPath], () => {
        void shell.openPath(path)
      })
      return
    }
  }
  try {
    await shell.openPath(path)
  } catch {
    // Ignore.
  }
}

async function findSessionTranscript(sessionId: string): Promise<string | null> {
  const projectsRoot = join(homedir(), '.claude', 'projects')
  try {
    const entries = await readdir(projectsRoot, { withFileTypes: true })
    for (const entry of entries) {
      if (!entry.isDirectory()) continue
      const candidate = join(projectsRoot, entry.name, `${sessionId}.jsonl`)
      try {
        const info = await stat(candidate)
        if (info.isFile()) return candidate
      } catch {
        // keep looking
      }
    }
  } catch {
    // no projects dir
  }
  return null
}

function createManager(tabId: string): SessionManager {
  return new SessionManager({
    emitEvent: (message: DesktopEvent) => send('session:event', { tabId, message }),
    emitState: (state: SessionState) => send('session:state', { tabId, state }),
    emitPermission: (request) => {
      send('permission:request', { tabId, request })
      if (mainWindow && !mainWindow.isFocused()) mainWindow.flashFrame(true)
    },
    emitPermissionCancel: (id) => send('permission:cancel', { tabId, id }),
    onResult: () => {
      // Notifications are shown from the renderer so they can include the tab title.
      // WSLg has no notification daemon; flashing the Windows taskbar is the
      // only remaining signal when the window is in the background.
      if (runningUnderWsl && mainWindow && !mainWindow.isFocused()) {
        mainWindow.flashFrame(true)
      }
    }
  })
}

function managerFor(tabId: string): SessionManager | undefined {
  return managers.get(tabId)
}

