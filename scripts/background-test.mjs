import { _electron as electron } from 'playwright-core'
const app = await electron.launch({ args: ['.', '--no-sandbox'], cwd: process.cwd(), env: { ...process.env, ELECTRON_ENABLE_LOGGING: '1' } })
const page = await app.firstWindow()
page.on('pageerror', e => console.log('[pageerror]', e.message))
await page.waitForLoadState('domcontentloaded')
await page.locator('.tabbar').waitFor({ state: 'visible', timeout: 20000 })
await page.getByRole('button', { name: '设置' }).click()
await page.locator('.settings-nav').getByRole('button', { name: '后台' }).click()
await page.locator('.background-panel').waitFor({ state: 'visible', timeout: 10000 })
await page.locator('.background-start .text-input').fill('/tmp/claude-desk-bg2')
await page.locator('.background-prompt').fill('只回复 BG_UI')
await page.locator('.background-trust input').check()
await page.getByRole('button', { name: '启动后台会话' }).click()
await page.waitForFunction(() => (document.querySelector('.background-start')?.textContent || '').includes('已启动后台会话'), undefined, { timeout: 120000 })
console.log('started:', (await page.locator('.background-start .settings-message').innerText()).replace(/\n/g, ' '))
await page.waitForTimeout(4000)
await page.getByRole('button', { name: '日志' }).last().click()
await page.locator('.background-logs').waitFor({ state: 'visible', timeout: 20000 })
console.log('logs:', (await page.locator('.background-logs').innerText()).slice(0, 300).replace(/\n/g, ' | '))
await page.screenshot({ path: '/tmp/opencode/ui-background.png' })
await page.locator('.background-logs-wrap').getByRole('button', { name: '关闭' }).click()
await page.getByRole('button', { name: '停止' }).last().click()
await page.waitForTimeout(2000)
console.log('sessions after stop:', await page.locator('.extension-row').count())
await page.locator('.extension-row .mini-button').last().click()
await page.waitForTimeout(1500)
console.log('sessions after remove:', await page.locator('.extension-row').count())
await app.close()
