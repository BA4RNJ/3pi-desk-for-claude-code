import { _electron as electron } from 'playwright-core'
const app = await electron.launch({ args: ['.', '--no-sandbox'], cwd: process.cwd(), env: { ...process.env, ELECTRON_ENABLE_LOGGING: '1' } })
const page = await app.firstWindow()
page.on('pageerror', e => console.log('[pageerror]', e.message))
await page.waitForLoadState('domcontentloaded')
await page.locator('.tabbar').waitFor({ state: 'visible', timeout: 20000 })
await page.getByRole('button', { name: '新建对话' }).click()
const input = page.getByPlaceholder(/给 Claude 发消息/)
await input.fill('请创建 /tmp/claude-desk-perm-test/proof.txt，内容为 ok，然后只回复 done')
await page.keyboard.press('Enter')
const bar = page.locator('.permission-bar')
await bar.waitFor({ state: 'visible', timeout: 120000 })
console.log('modal backdrops:', await page.locator('.modal-backdrop').count())
console.log('bar:', (await bar.innerText()).slice(0, 400).replace(/\n/g, ' | '))
await page.screenshot({ path: '/tmp/opencode/ui-permission-bar.png' })
await page.locator('.permission-bar').getByRole('button', { name: '允许一次' }).click()
await page.waitForFunction(() => document.querySelectorAll('.tool-card.tool-done').length > 0, undefined, { timeout: 180000 })
console.log('allowed, tool done; bar left:', await page.locator('.permission-bar').count())
await page.screenshot({ path: '/tmp/opencode/ui-permission-bar-done.png' })
await app.close()
