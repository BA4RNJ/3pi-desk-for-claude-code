import { _electron as electron } from 'playwright-core'
const app = await electron.launch({ args: ['.', '--no-sandbox'], cwd: process.cwd(), env: { ...process.env, ELECTRON_ENABLE_LOGGING: '1' } })
const page = await app.firstWindow()
page.on('pageerror', e => console.log('[pageerror]', e.message))
await page.waitForLoadState('domcontentloaded')
await page.locator('.tabbar').waitFor({ state: 'visible', timeout: 20000 })
await page.getByRole('button', { name: '新建对话' }).click()
const input = page.getByPlaceholder(/给 Claude 发消息/)
await input.fill('请调用 AskUserQuestion 工具问我一个二选一问题：选苹果还是香蕉，然后只回复我选择的选项。')
await page.keyboard.press('Enter')
const dialog = page.locator('.question-dialog')
await dialog.waitFor({ state: 'visible', timeout: 120000 })
console.log('question:', (await dialog.innerText()).slice(0, 500).replace(/\n/g, ' | '))
await page.locator('.question-option').first().click()
await page.getByRole('button', { name: '发送回答' }).click()
await page.waitForFunction(() => !document.querySelector('.working-chip'), undefined, { timeout: 180000 })
console.log('reply:', (await page.locator('.message-assistant').last().innerText()).slice(0, 200).replace(/\n/g, ' | '))
await page.screenshot({ path: '/tmp/opencode/ui-question.png' })

await input.fill('/')
await page.locator('.slash-menu').waitFor({ state: 'visible', timeout: 10000 })
console.log('slash commands:', await page.locator('.slash-item').count())
console.log('slash first:', (await page.locator('.slash-item').first().innerText()).replace(/\n/g, ' | '))
await page.screenshot({ path: '/tmp/opencode/ui-slash.png' })
await page.keyboard.press('Escape')
await app.close()
